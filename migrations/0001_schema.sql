-- UniCloud Portal schema (PostgreSQL). Vocabulary: GLOSSARY.md. Design: openspec/changes/rust-rewrite/design.md

CREATE TABLE faculties (
    code  VARCHAR(16)  PRIMARY KEY,
    name  VARCHAR(200) NOT NULL
);

CREATE TABLE specialties (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_code  VARCHAR(16)  NOT NULL REFERENCES faculties (code),
    name          VARCHAR(200) NOT NULL,
    UNIQUE (faculty_code, name)
);

CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 VARCHAR(254) NOT NULL UNIQUE,
    password_hash         VARCHAR(255) NOT NULL,
    first_name            VARCHAR(100) NOT NULL,
    last_name             VARCHAR(100) NOT NULL,
    role                  VARCHAR(16)  NOT NULL CHECK (role IN ('STUDENT', 'TEACHER', 'DEAN', 'INSPECTOR', 'ADMIN')),
    permissions_mask      BIGINT       NOT NULL DEFAULT 0,
    -- Teachers, deans and inspectors belong to one faculty. Students get theirs from the specialty.
    faculty_code          VARCHAR(16)  REFERENCES faculties (code),
    must_change_password  BOOLEAN      NOT NULL DEFAULT FALSE,
    enabled               BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- A faculty has at most one dean
CREATE UNIQUE INDEX one_dean_per_faculty ON users (faculty_code) WHERE role = 'DEAN' AND enabled;

CREATE TABLE academic_records (
    user_id         BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    faculty_number  VARCHAR(20) NOT NULL UNIQUE,
    specialty_id    INTEGER     NOT NULL REFERENCES specialties (id),
    study_year      SMALLINT    NOT NULL CHECK (study_year BETWEEN 1 AND 6),
    status          VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INTERRUPTED', 'GRADUATED'))
);

CREATE TABLE courses (
    code          VARCHAR(16)  PRIMARY KEY,
    title         VARCHAR(200) NOT NULL,
    ects_credits  SMALLINT     NOT NULL CHECK (ects_credits BETWEEN 1 AND 30),
    faculty_code  VARCHAR(16)  NOT NULL REFERENCES faculties (code)
);

CREATE TABLE course_offerings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code     VARCHAR(16) NOT NULL REFERENCES courses (code),
    semester        VARCHAR(16) NOT NULL,
    teacher_id      BIGINT      NOT NULL REFERENCES users (id),
    capacity        INTEGER     NOT NULL CHECK (capacity > 0),
    enrolled_count  INTEGER     NOT NULL DEFAULT 0,
    is_open         BOOLEAN     NOT NULL DEFAULT TRUE,
    UNIQUE (course_code, semester, teacher_id),
    -- The last line of defence against overselling
    CHECK (enrolled_count BETWEEN 0 AND capacity)
);
CREATE INDEX course_offerings_semester ON course_offerings (semester);
CREATE INDEX course_offerings_teacher ON course_offerings (teacher_id);

CREATE TABLE enrollments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   BIGINT      NOT NULL REFERENCES users (id),
    offering_id  BIGINT      NOT NULL REFERENCES course_offerings (id),
    status       VARCHAR(16) NOT NULL DEFAULT 'ENROLLED' CHECK (status IN ('ENROLLED', 'CANCELLED', 'REJECTED')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_by   BIGINT      REFERENCES users (id),
    UNIQUE (student_id, offering_id)
);
CREATE INDEX enrollments_offering ON enrollments (offering_id) WHERE status = 'ENROLLED';

-- Modules registered for single sign-on (docs/sso.md)
CREATE TABLE oauth_clients (
    client_id                  VARCHAR(63)  PRIMARY KEY,
    name                       VARCHAR(200) NOT NULL,
    -- SHA-256 of the 256-bit random secret, hex. High entropy, so no slow hash is needed.
    secret_hash                CHAR(64)     NOT NULL,
    redirect_uris              TEXT[]       NOT NULL,
    post_logout_redirect_uris  TEXT[]       NOT NULL DEFAULT '{}',
    directory_access           BOOLEAN      NOT NULL DEFAULT FALSE,
    registered_by              VARCHAR(64)  NOT NULL,
    created_at                 TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- One completed login of a user into a module. Kept 24 hours (logout id_token_hint, replay revocation).
CREATE TABLE oauth_grants (
    id            UUID         PRIMARY KEY,
    client_id     VARCHAR(63)  NOT NULL REFERENCES oauth_clients (client_id) ON DELETE CASCADE,
    user_id       BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    scope         TEXT         NOT NULL,
    session_id    VARCHAR(64)  NOT NULL,
    access_jti    UUID,
    id_token_jti  UUID,
    revoked       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX oauth_grants_access_jti ON oauth_grants (access_jti);
CREATE INDEX oauth_grants_id_token_jti ON oauth_grants (id_token_jti);
CREATE INDEX oauth_grants_created ON oauth_grants (created_at);

-- Authorization codes: only the SHA-256 of the code is stored. 60 seconds, single use.
CREATE TABLE oauth_codes (
    code_hash       CHAR(64)     PRIMARY KEY,
    grant_id        UUID         NOT NULL REFERENCES oauth_grants (id) ON DELETE CASCADE,
    redirect_uri    TEXT         NOT NULL,
    nonce           TEXT,
    code_challenge  VARCHAR(128) NOT NULL,
    auth_time       BIGINT       NOT NULL,
    expires_at      TIMESTAMPTZ  NOT NULL,
    redeemed_at     TIMESTAMPTZ
);

-- Client-credentials tokens for the directory API, so they can be revoked with the client
CREATE TABLE oauth_client_tokens (
    jti         UUID         PRIMARY KEY,
    client_id   VARCHAR(63)  NOT NULL REFERENCES oauth_clients (client_id) ON DELETE CASCADE,
    expires_at  TIMESTAMPTZ  NOT NULL
);
